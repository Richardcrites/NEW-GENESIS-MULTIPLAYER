    // Guard #4 - RVA 0xB7CF10 condition/filter evaluator (co-op vehicle-enter)
    // -------------------------------------------------------------------
    // Crash pattern (, 2026-06-21, two dumps 77a475ce + d654d645):
    //   FUN_140b7d650(obj, ctx): takes a slim-RW lock at obj+0xA8 (FUN_1422ce9b0,
    //   the known engine null-lock CTD family), reads a container pointer at
    //   obj+0xA0, then walks its elements (count@+0x28, data@+0x30, stride 0x28)
    //   running a per-element condition matcher (FUN_140b6bc80). Crashing instr
    //   @ +0x4D: `mov eax,[container+0x28]` - `container` (= *(obj+0xA0)) is a
    //   DANGLING pointer to freed+unmapped memory (obj itself is valid: the lock
    //   acquire above succeeded). Triggered on ActionInteractionEnter (client
    //   entering a vehicle/furniture) in co-op; the dangling entry traces to a
    //   PULSAR actor despawn (clone respawn churn / NPC) that wasn't cleanly
    //   removed from this engine list. Same 0x1422CC350 family that parked
    //   space-follow. Proper de-register is unidentified RE; shield meanwhile.
    //
    // Guard strategy: before dispatching to the original, SEH-probe exactly the
    // fields it will dereference (the container ptr, its count, its data ptr, and
    // first/last element bytes). If any probe faults or the values are insane,
    // the container is dangling → return 1 (the function's own "empty list →
    // all-conditions-pass" value, see decomp) WITHOUT walking → no crash. The
    // shield only fires in the already-corrupted state, so a normal eval is
    // 100% unchanged; a shielded eval costs at most one over-permissive result.
    using CondEvalFn = uintptr_t(__fastcall*)(uintptr_t, uintptr_t);
    static CondEvalFn s_origCondEval = nullptr;
    static std::atomic<uint64_t> s_condEvalHits{0};
    static std::atomic<uint64_t> s_condEvalLastLogMs{0};

    // One-shot ROOT-CAUSE diagnostic (2026-06-27): the subject `obj` was already
    // CONFIRMED = the vehicle FURN (formID 0xFF016497, vtblRVA 0x4B95FB8) - NOT the
    // clone. The remaining question is WHICH FORM in the FURN's +0xA0 condition
    // list is dangling: the engine matcher (0x140b6b560) reads each element's
    // form-ptr at +8 and derefs it raw after only a NULL-check, so a -1 sentinel
    // CTDs (dump 3a2dc104 @0xB6B5AB). We now (a) validate every element's +8 so
    // Guard #4 also catches the element-level crash (fires right at sit-down), and
    // (b) one-shot log the bad element's identity. element+0 is a second form ptr;
    // if it is still live its vtable+FormID names the dangling form.
    static std::atomic<bool> s_condEvalDiagDone{false};
    static std::atomic<bool> s_condEvalElemDiagDone{false};

    // Pure-SEH POD capture (no PLOG -> no C2712 next to __try).
    static bool ProbeObjId(uintptr_t obj, uintptr_t* outVtbl, uint32_t* outFormId) noexcept
    {
        __try {
            *outVtbl    = *reinterpret_cast<volatile uintptr_t*>(obj);          // vtable ptr (if polymorphic)
            *outFormId  = *reinterpret_cast<volatile uint32_t*>(obj + 0x28);    // TESForm.formID @ +0x28
            return true;
        } __except (EXCEPTION_EXECUTE_HANDLER) {
            return false;
        }
    }

    struct ElemDiag {
        uintptr_t p0, p8, p10, p18;   // raw element qwords (stride 0x28)
        uintptr_t v0; uint32_t fid0;  // element+0 form (keyword?): vtable + FormID
        uintptr_t v8; uint32_t fid8;  // element+8 form (the dangling one): vtable + FormID
        bool v0ok, v8ok;
    };
    static bool ProbeFormId(uintptr_t p, uintptr_t* vt, uint32_t* fid) noexcept
    {
        __try {
            if (p > 0x10000 && p != static_cast<uintptr_t>(-1)) {
                *vt  = *reinterpret_cast<volatile uintptr_t*>(p);          // vtable
                *fid = *reinterpret_cast<volatile uint32_t*>(p + 0x28);    // FormID
                return true;
            }
        } __except (EXCEPTION_EXECUTE_HANDLER) {}
        return false;
    }
    static bool ProbeBadElem(uintptr_t el, ElemDiag* d) noexcept
    {
        __try {
            d->p0  = *reinterpret_cast<volatile uintptr_t*>(el + 0x00);
            d->p8  = *reinterpret_cast<volatile uintptr_t*>(el + 0x08);
            d->p10 = *reinterpret_cast<volatile uintptr_t*>(el + 0x10);
            d->p18 = *reinterpret_cast<volatile uintptr_t*>(el + 0x18);
        } __except (EXCEPTION_EXECUTE_HANDLER) {
            return false;
        }
        d->v0 = d->v8 = 0; d->fid0 = d->fid8 = 0;
        d->v0ok = ProbeFormId(d->p0, &d->v0, &d->fid0);   // separate __try each
        d->v8ok = ProbeFormId(d->p8, &d->v8, &d->fid8);
        return true;
    }

    static inline bool IsBadFormPtr(uintptr_t p) noexcept
    {
        // 0 is the engine's own handled null; the -1 sentinel or any sub-page
        // value is an invalidated/dangling form ptr that the matcher derefs raw.
        return p == static_cast<uintptr_t>(-1) || (p != 0 && p < 0x10000);
    }

    // Starfield.exe image range (cached) so we can validate that a form-ptr's
    // vtable points into engine code. A FREED form whose ptr still looks like a
    // plausible heap address (dump 3436d016: form-ptr deref gave vtable
    // 0x1000000011 -> call faults) is NOT caught by IsBadFormPtr; its vtable is
    // outside the module, so a range check catches the use-after-free.
    static uintptr_t s_sfBase = 0, s_sfEnd = 0;
    static void EnsureSfRange() noexcept
    {
        if (s_sfBase) return;
        uintptr_t b = reinterpret_cast<uintptr_t>(GetModuleHandleA("Starfield.exe"));
        if (!b) return;
        uint32_t size = 0x9000000;  // generous fallback (actual ~0x8988000)
        __try {
            auto dos = reinterpret_cast<const IMAGE_DOS_HEADER*>(b);
            auto nt  = reinterpret_cast<const IMAGE_NT_HEADERS*>(b + dos->e_lfanew);
            size = nt->OptionalHeader.SizeOfImage;
        } __except (EXCEPTION_EXECUTE_HANDLER) {}
        s_sfBase = b; s_sfEnd = b + size;
    }
    static inline bool VtblInModule(uintptr_t vt) noexcept
    {
        return s_sfBase && vt >= s_sfBase && vt < s_sfEnd;
    }

    // SEH-wrapped dispatch to an original condition evaluator. The per-guard
    // pre-probe catches the COMMON already-dangling case WITHOUT taking the
    // engine lock (it returns before calling the original). This helper adds
    // coverage for the TOCTOU case: the condition list freed by despawn churn
    //  AFTER the probe but DURING the original's own walk - observed dump
    // 6914f5ed @ RVA 0xB7CF5D (revive in combat, list freed between the probe and
    // the count read). On a mid-eval fault we return the guard's benign value.
    // These evaluators only READ the list (read-lock on an object that is being
    // torn down), so a missed unlock on that one dying object is far cheaper than
    // a hard CTD. POD locals only -> __try has no C++ unwinding (no C2712).
    static std::atomic<uint64_t> s_condEvalSeh{0};
    static std::atomic<uint64_t> s_condEvalSehLogMs{0};
    static uintptr_t SafeCallCondEval(CondEvalFn fn, uintptr_t a, uintptr_t b,
                                      uintptr_t benign) noexcept
    {
        bool caught = false;
        uintptr_t r = benign;
        __try {
            r = fn(a, b);
        } __except (EXCEPTION_EXECUTE_HANDLER) {
            caught = true;
        }
        if (!caught) return r;
        const uint64_t n = s_condEvalSeh.fetch_add(1, std::memory_order_relaxed) + 1;
        const uint64_t now = GetTickCount64();
        uint64_t last = s_condEvalSehLogMs.load(std::memory_order_relaxed);
        if (now - last > 5000 &&
            s_condEvalSehLogMs.compare_exchange_strong(last, now,
                                                       std::memory_order_relaxed))
        {
            PLOG_DIAG("[PULSAR] CrashGuard: CondEval SEH-caught {} mid-eval faults "
                      "(despawn race)"sv, n);
        }
        return benign;
    }

    static uintptr_t __fastcall HookedCondEval(uintptr_t obj, uintptr_t ctx)
    {
        bool shield = false;
        uintptr_t badElem = 0;
        EnsureSfRange();
        __try {
            uintptr_t container = *reinterpret_cast<uintptr_t*>(obj + 0xA0);
            if (container != 0) {
                const uint32_t  count = *reinterpret_cast<volatile uint32_t*>(container + 0x28);
                const uintptr_t data  = *reinterpret_cast<volatile uintptr_t*>(container + 0x30);
                if (count > 0x100000) {
                    shield = true;                       // insane element count
                } else if (count != 0) {
                    if (data == 0) {
                        shield = true;                   // count but null data
                    } else {
                        // Validate EACH element's form-ptr (+8): the matcher derefs
                        // it raw after only a NULL-check, so a -1 sentinel CTDs (and
                        // a freed-but-plausible ptr CTDs one instr later at the
                        // vtable call). Catch both: bad ptr value, OR a ptr whose
                        // vtable is not inside Starfield.exe (= freed form).
                        for (uint32_t i = 0; i < count; ++i) {
                            const uintptr_t el = data + static_cast<uintptr_t>(i) * 0x28;
                            const uintptr_t fp = *reinterpret_cast<volatile uintptr_t*>(el + 8);
                            if (IsBadFormPtr(fp)) { shield = true; badElem = el; break; }
                            if (fp != 0) {
                                const uintptr_t vt = *reinterpret_cast<volatile uintptr_t*>(fp);
                                if (!VtblInModule(vt)) { shield = true; badElem = el; break; }
                            }
                        }
                    }
                }
            }
        } __except (EXCEPTION_EXECUTE_HANDLER) {
            shield = true;                               // probe faulted = dangling list/element
        }

        if (shield) {
            // One-shot identity capture of the dangling subject (obj = vehicle FURN).
            bool expected = false;
            if (s_condEvalDiagDone.compare_exchange_strong(expected, true,
                                                           std::memory_order_relaxed))
            {
                uintptr_t vt = 0; uint32_t fid = 0;
                if (ProbeObjId(obj, &vt, &fid)) {
                    uintptr_t base = reinterpret_cast<uintptr_t>(GetModuleHandleA("Starfield.exe"));
                    PLOG_WARN("[PULSAR] CrashGuard #4 DIAG (subject): obj=0x{:x} "
                              "vtblRVA=0x{:x} formID=0x{:08x}"sv,
                              obj, (base && vt > base) ? (vt - base) : vt, fid);
                } else {
                    PLOG_WARN("[PULSAR] CrashGuard #4 DIAG (subject): obj=0x{:x} "
                              "identity probe faulted"sv, obj);
                }
            }
            // One-shot identity capture of the BAD ELEMENT (which form is -1).
            if (badElem) {
                bool e2 = false;
                if (s_condEvalElemDiagDone.compare_exchange_strong(e2, true,
                                                                   std::memory_order_relaxed))
                {
                    ElemDiag d{};
                    uintptr_t base = reinterpret_cast<uintptr_t>(GetModuleHandleA("Starfield.exe"));
                    if (ProbeBadElem(badElem, &d)) {
                        PLOG_WARN("[PULSAR] CrashGuard #4 DIAG (bad element): el=0x{:x} "
                                  "p0=0x{:x} p8=0x{:x} p10=0x{:x} p18=0x{:x}"sv,
                                  badElem, d.p0, d.p8, d.p10, d.p18);
                        // p0 = likely the keyword (still live -> which condition).
                        PLOG_WARN("[PULSAR] CrashGuard #4 DIAG (bad element) form@p0: "
                                  "live={} vtblRVA=0x{:x} formID=0x{:08x}"sv,
                                  d.v0ok, (base && d.v0 > base) ? (d.v0 - base) : d.v0, d.fid0);
                        // p8 = the dangling form (freed -> vtbl out of module / unreadable).
                        PLOG_WARN("[PULSAR] CrashGuard #4 DIAG (bad element) form@p8: "
                                  "live={} vtblRVA=0x{:x} formID=0x{:08x}"sv,
                                  d.v8ok, (base && d.v8 > base) ? (d.v8 - base) : d.v8, d.fid8);
                    } else {
                        PLOG_WARN("[PULSAR] CrashGuard #4 DIAG (bad element): el=0x{:x} probe faulted"sv,
                                  badElem);
                    }
                }
            }
            const uint64_t n = s_condEvalHits.fetch_add(1, std::memory_order_relaxed) + 1;
            const uint64_t now = GetTickCount64();
            uint64_t last = s_condEvalLastLogMs.load(std::memory_order_relaxed);
            if (now - last > 5000 &&
                s_condEvalLastLogMs.compare_exchange_strong(last, now,
                                                            std::memory_order_relaxed))
            {
                PLOG_DIAG("[PULSAR] CrashGuard: CondEval shielded {} dangling-list calls "
                          "(co-op vehicle/furniture-enter)"sv, n);
            }
            return 1;  // = engine's empty-list / conditions-pass result
        }
        return SafeCallCondEval(s_origCondEval, obj, ctx, 1);  // SEH-wrapped: also catches TOCTOU mid-eval free
    }

