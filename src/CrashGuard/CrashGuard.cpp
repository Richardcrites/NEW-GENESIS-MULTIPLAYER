    static char __fastcall HookedInvTeardown(uintptr_t pStruct, uint8_t flag)
    {
        bool shield = false;
        __try {
            uintptr_t refr = *reinterpret_cast<volatile uintptr_t*>(pStruct);  // rbx = *pStruct
            if (refr != 0) {
                uintptr_t list = *reinterpret_cast<volatile uintptr_t*>(refr + 0xA0);
                if (list != 0) {
                    // the crashing deref: cmp [list+0x10],0 - faults if list freed
                    volatile uintptr_t probe = *reinterpret_cast<volatile uintptr_t*>(list + 0x10);
                    (void)probe;
                }
            }
        } __except (EXCEPTION_EXECUTE_HANDLER) {
            shield = true;  // obj or its +0xA0 list is dangling/unmapped
        }

        if (shield) {
            LogInvTeardownShield();
            return 0;  // = fn's own no-op exit (xor al,al), lock never acquired
        }
        return s_origInvTeardown(pStruct, flag);
    }

